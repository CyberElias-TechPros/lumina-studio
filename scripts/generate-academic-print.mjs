#!/usr/bin/env node
/**
 * Build printable, self-contained A4 HTML from the academic Markdown tree.
 * Output: academic/print/<mirrored path>.html + academic/print/index.html
 * Usage: npm run academic:print   (output is generated; do not commit academic/print/)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync } from "node:fs";
import { join, relative, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { unified } from "unified";
import remarkParse from "remark-parse";
import remarkGfm from "remark-gfm";
import remarkRehype from "remark-rehype";
import rehypeStringify from "rehype-stringify";

const root = fileURLToPath(new URL("../", import.meta.url));
const SRC = join(root, "academic");
const OUT = join(SRC, "print");

function walk(dir) {
  const entries = [];
  for (const name of readdirSync(dir)) {
    if (name === "print" || name === ".work") continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) entries.push(...walk(full));
    else if (extname(name) === ".md") entries.push(full);
  }
  return entries;
}

function docLeg(raw, fallback) {
  const id = raw.match(/Document ID\s*\|\s*([^|\n]+)/i)?.[1]?.trim();
  const version = raw.match(/\|\s*Version\s*\|\s*([^|\n]+)/i)?.[1]?.trim();
  return (
    [id, version ? `v${version.replace(/^v/i, "")}` : null].filter(Boolean).join(" · ") || fallback
  );
}

const css = `
@page {
  size: A4;
  margin: 19mm 17mm 23mm 17mm;
  @bottom-left { content: string(docid); font: 8pt Georgia, serif; color: #5a6a7c; }
  @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 8pt Georgia, serif; color: #5a6a7c; }
}
@page :first { margin-top: 24mm; }
* { box-sizing: border-box; }
body {
  font: 10.5pt/1.35 Georgia, "Times New Roman", serif;
  color: #16202c; margin: 0 auto; max-width: 172mm; padding: 0 4mm 8mm; background: #fff;
}
.docid-leg { position: absolute; left: -9999px; top: 0; font-size: 1pt; string-set: docid content(text); }
.gen-note { font: italic 8pt/1.4 Georgia, serif; color: #7c8a99; border-bottom: 0.4pt solid #d8dee8; padding-bottom: 3mm; margin-bottom: 5mm; }
h1, h2, h3, h4 { font-family: Georgia, serif; color: #0d2b52; page-break-after: avoid; line-height: 1.2; }
h1 { font-size: 21pt; border-bottom: 2.2pt solid #1d5ae0; padding-bottom: 2mm; }
h2 { font-size: 14.5pt; margin-top: 7mm; text-transform: none; border-bottom: 0.6pt solid #cdd6e4; padding-bottom: 1mm; }
h3 { font-size: 11.5pt; margin-top: 5mm; }
p, li { text-align: left; } ul, ol { padding-left: 6mm; }
code { font: 9pt "Courier New", monospace; background: #f1f4f9; padding: 0 3pt; border-radius: 2pt; }
pre code { display: block; padding: 3mm 4mm; overflow-wrap: anywhere; white-space: pre-wrap; }
pre { background: #f1f4f9; border: 0.4pt solid #d8dee8; padding: 0; }
table { width: 100%; border-collapse: collapse; font-size: 9pt; margin: 4mm 0; page-break-inside: auto; }
th, td { border: 0.4pt solid #c3ccda; padding: 2.2pt 5pt; vertical-align: top; text-align: left; }
th { background: #e8edf5; color: #0d2b52; font-family: Georgia, serif; }
tr { page-break-inside: avoid; } tr:nth-child(even) td { background: #fafbfe; }
blockquote { border-left: 3pt solid #1d5ae0; margin-left: 0; padding: 1mm 4mm; color: #33415a; background: #f6f8fd; }
a { color: #1d5ae0; text-decoration: none; }
hr { border: 0; border-top: 0.4pt solid #d8dee8; margin: 6mm 0; }
@media screen { body { padding-top: 6mm; } .gen-note { display: block; } }
@media print { .gen-note { display: none; } a { color: inherit; } }
`;

const escapeHtml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const processor = unified().use(remarkParse).use(remarkGfm).use(remarkRehype).use(rehypeStringify);

const files = walk(SRC).sort();
const entries = [];

rmSync(OUT, { recursive: true, force: true });

for (const file of files) {
  const raw = readFileSync(file, "utf8");
  const html = String(await processor.process(raw));
  const rel = relative(SRC, file).replace(/\.md$/, ".html");
  const target = join(OUT, rel);
  mkdirSync(dirname(target), { recursive: true });
  const title = raw.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? basename(file, ".md");
  const leg = escapeHtml(docLeg(raw, "Cyber Elias Academy"));
  const page = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)} — Cyber Elias Academy</title><style>${css}</style></head>
<body><span class="docid-leg">${leg}</span>
<p class="gen-note">Generated from <code>academic/${relative(SRC, file).replace(/\\/g, "/")}</code>. Edit the Markdown source — do not edit this file. Use your browser's Print → Save as PDF for a PDF copy.</p>
${html}
</body></html>`;
  writeFileSync(target, page);
  entries.push({ rel: rel.replace(/\\/g, "/"), title: title.replace(/^CEA\s+/, "") });
}

const grouped = new Map();
for (const e of entries) {
  const top = e.rel.split("/")[0];
  if (!grouped.has(top)) grouped.set(top, []);
  grouped.get(top).push(e);
}
const listHtml = [...grouped.entries()]
  .map(
    ([group, items]) =>
      `<h2>${escapeHtml(group)}</h2>\n<ul>\n${items
        .map((i) => `  <li><a href="${i.rel}">${escapeHtml(i.title)}</a></li>`)
        .join("\n")}\n</ul>`,
  )
  .join("\n");

writeFileSync(
  join(OUT, "index.html"),
  `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>CEA Academic Library (internal) — Cyber Elias Academy</title><style>${css}</style></head>
<body><span class="docid-leg">CEA Academic Library · internal</span>
<p class="gen-note">Internal academy documentation. Generated; do not edit or commit this directory.</p>
<h1>CEA Academic Library</h1>
<p>${entries.length} documents. Print any document from its page with your browser (Print → Save as PDF). Codes follow the CEA academic document ID scheme: SPEC (specification) · MAN (manual) · NOTE (lesson notes) · GUI (instructor guide) · WB (workbook) · QA (assessment) · FP (final project) · RUB (rubric) · GLO (glossary) · LMS (portal structure).</p>
${listHtml}
</body></html>`,
);
console.log(`academic/print: ${entries.length} documents built`);
