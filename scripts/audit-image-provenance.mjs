/**
 * Image provenance audit.
 *
 * Every image on the public site must be traceable to an owner, a licence or a
 * generation event. Unlicensed imagery is a listed AdSense policy violation, and
 * "we think these are ours" is not a record.
 *
 * The registry (src/data/editorial/image-provenance.json) holds directory rules
 * and per-file overrides. Anything not covered is UNKNOWN and must be resolved by
 * a person who knows where the file came from.
 *
 * Usage:
 *   node scripts/audit-image-provenance.mjs            # report + write markdown
 *   node scripts/audit-image-provenance.mjs --strict   # exit 1 if any unknown
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const imagesRoot = join(root, "public/images");
const registryFile = join(root, "src/data/editorial/image-provenance.json");
const reportFile = join(root, "docs/image-provenance-report.md");
const strict = process.argv.includes("--strict");

const registry = existsSync(registryFile)
  ? JSON.parse(readFileSync(registryFile, "utf8"))
  : { directories: [], files: {} };

const EXT = /\.(jpe?g|png|webp|avif|gif|svg)$/i;

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const absolute = join(dir, entry);
    const stats = statSync(absolute);
    if (stats.isDirectory()) walk(absolute, out);
    else if (EXT.test(entry)) out.push(absolute);
  }
  return out;
}

const files = existsSync(imagesRoot) ? walk(imagesRoot) : [];

function classify(publicPath) {
  const override = registry.files?.[publicPath];
  if (override) return { ...override, source: "per-file record" };
  for (const rule of registry.directories ?? []) {
    if (publicPath.startsWith(rule.prefix))
      return { ...rule, source: `directory rule ${rule.prefix}` };
  }
  return {
    status: "unknown",
    holder: null,
    note: "No provenance record. A person must state where this file came from.",
    source: "unrecorded",
  };
}

const rows = files.map((absolute) => {
  const publicPath = `/${relative(join(root, "public"), absolute).split("\\").join("/")}`;
  const record = classify(publicPath);
  const bytes = statSync(absolute).size;
  return { publicPath, bytes, ...record };
});

const byStatus = rows.reduce((acc, row) => {
  acc[row.status] = (acc[row.status] ?? 0) + 1;
  return acc;
}, {});

const unknown = rows.filter((row) => row.status === "unknown");
const totalMb = rows.reduce((n, row) => n + row.bytes, 0) / (1024 * 1024);
const oversized = rows.filter((row) => row.bytes > 300 * 1024);

const statusOrder = ["owned", "generated", "licensed", "owner-supplied", "unknown"];
const lines = [
  "# Image provenance report",
  "",
  "Generated by `npm run audit:images`. Do not edit by hand — edit",
  "`src/data/editorial/image-provenance.json` and re-run.",
  "",
  `Generated: ${new Date().toISOString().slice(0, 10)} · files: ${rows.length} · total: ${totalMb.toFixed(1)} MB`,
  "",
  "## Summary",
  "",
  "| Status | Files |",
  "| --- | ---: |",
  ...statusOrder.filter((s) => byStatus[s]).map((s) => `| ${s} | ${byStatus[s]} |`),
  "",
];

if (unknown.length) {
  lines.push(
    "## Unresolved — must be recorded or replaced",
    "",
    "These files have no provenance. For each one, a person must record one of:",
    "*photographed by the Academy (date, photographer)* · *generated by <tool> on <date>* ·",
    "*licensed from <source>, licence #<id>*. If none applies, replace the file.",
    "",
    "| File | Size |",
    "| --- | ---: |",
    ...unknown
      .sort((a, b) => b.bytes - a.bytes)
      .map((row) => `| \`${row.publicPath}\` | ${Math.round(row.bytes / 1024)} KB |`),
    "",
  );
} else {
  lines.push("## Unresolved", "", "None. Every image has a recorded origin.", "");
}

if (oversized.length) {
  lines.push(
    "## Weight warnings (over 300 KB)",
    "",
    "Not a policy issue, but a mobile data cost for the reader.",
    "",
    "| File | Size |",
    "| --- | ---: |",
    ...oversized
      .sort((a, b) => b.bytes - a.bytes)
      .slice(0, 40)
      .map((row) => `| \`${row.publicPath}\` | ${Math.round(row.bytes / 1024)} KB |`),
    "",
  );
}

lines.push(
  "## Directory rules in force",
  "",
  "| Prefix | Status | Holder | Note |",
  "| --- | --- | --- | --- |",
  ...(registry.directories ?? []).map(
    (rule) =>
      `| \`${rule.prefix}\` | ${rule.status} | ${rule.holder ?? "—"} | ${rule.note ?? "—"} |`,
  ),
  "",
);

writeFileSync(reportFile, lines.join("\n"));

console.log(`Image provenance — ${rows.length} files, ${totalMb.toFixed(1)} MB`);
for (const status of statusOrder) {
  if (byStatus[status]) console.log(`  ${status.padEnd(18)} ${byStatus[status]}`);
}
console.log(`  over 300 KB        ${oversized.length}`);
console.log(`Report: ${relative(root, reportFile)}`);

if (unknown.length) {
  console.log(
    `\n${unknown.length} file(s) have no recorded origin. See the report; replace or record them before an AdSense review.`,
  );
  if (strict) process.exit(1);
}
