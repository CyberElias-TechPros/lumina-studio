/** Generate offer metadata and additive, content-only LMS templates. Never seeds users or money. */
import { URL } from "node:url";
import { writeFileSync } from "node:fs";
import { allCourses } from "../../src/data/academy/catalog";
import { longformPrograms } from "../../src/data/academy/longform";

const offers = Object.fromEntries([
  ...allCourses.map((c) => [
    c.slug,
    { title: c.title, kind: "short", fee: c.fee, weeks: c.weeks, daysPerWeek: 2 },
  ]),
  ...longformPrograms.map((c) => [
    c.slug,
    { title: c.title, kind: "long", fee: c.fee, weeks: c.weeks, daysPerWeek: c.daysPerWeek },
  ]),
]);
writeFileSync(
  new URL("../src/lib/tuition-offers.generated.ts", import.meta.url),
  "// Generated by npm run gen:tuition. Catalogue/longform are the price authority.\n" +
    'export const PROGRAMS: Record<string, { title: string; kind: "short" | "long"; fee: number; weeks: number; daysPerWeek: number }> = ' +
    JSON.stringify(offers, null, 2) +
    ";\n",
);
const quote = (v: string) => "'" + v.replace(/'/g, "''") + "'";
const sql = allCourses
  .map((c) => {
    const modules = [
      {
        id: `${c.slug}-curriculum`,
        title: c.title,
        lessons: c.sessions.map((s) => ({
          id: s.slug,
          title: s.title,
          type: "lesson",
          duration: `${s.minutes} min`,
          status: "locked",
          body: `Study the published class notes and practice task: https://www.cea.ng/classes/${c.slug}/${s.slug}. Instructor-led assessment follows the assignment brief in your learner workspace.`,
        })),
      },
    ];
    return `INSERT OR IGNORE INTO courses (slug, title, subtitle, modules) VALUES (${quote(c.slug)}, ${quote(c.title)}, ${quote("Practical academy course · see your accepted offer for timetable and equipment")}, ${quote(JSON.stringify(modules))});`;
  })
  .join("\n");
writeFileSync(
  new URL("../seeds/academy-courses.sql", import.meta.url),
  "-- Content only. Add missing academy templates without replacing progress or existing course versions.\n" +
    sql +
    "\n",
);
writeFileSync(
  new URL("../seeds/academy-courses.ts", import.meta.url),
  "// Generated by npm run gen:tuition.\nexport const academyCoursesSql = " +
    JSON.stringify(sql) +
    ";\n",
);
console.log(
  `${Object.keys(offers).length} unchanged offers; ${allCourses.length} additive academy course templates.`,
);
